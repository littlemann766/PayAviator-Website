import random, math, json
# layer: name, top%, h(vh,vw-min), period s, clouds, width range, base-y range, alpha, haze, seed, puffs
LAYERS=[
 dict(n='far', top=3, vh=38, dur=170, clouds=6, w=(0.8,1.15), yb=(0.55,0.9), a=0.60, haze=0.55, seed=11, pf=7),
 dict(n='mist',top=28,vh=50, dur=230, clouds=4, w=(1.3,1.8), yb=(0.75,0.95), a=0.13, haze=0.0, seed=5, pf=5, mist=True),
 dict(n='mid', top=53,vh=40, dur=110, clouds=4, w=(1.0,1.35), yb=(0.6,0.95), a=0.72, haze=0.25, seed=23, pf=9),
 dict(n='near',top=68,vh=40, dur=70, clouds=3, w=(1.5,1.9), yb=(0.85,1.0), a=0.96, haze=0.0, seed=37, pf=11),
 dict(n='front',top=85,vh=30, dur=44, clouds=3, w=(1.6,2.1), yb=(0.9,1.02), a=1.0, haze=0.0, seed=41, pf=11),
]
SKY=(96,158,222)
def mix(a,b,t): return tuple(round(a[i]*(1-t)+b[i]*t) for i in range(3))
def gen(L):
    r=random.Random(L['seed']); out=[]
    slot=4.0/L['clouds']
    for k in range(L['clouds']):
        cw=r.uniform(*L['w']); cx=slot*(k+.5)+r.uniform(-.12,.12)*slot
        yb=r.uniform(*L['yb']); n=L['pf']; ps=[]
        for i in range(n):
            u=(i+.5)/n; dome=math.sin(math.pi*u)**0.9
            if L.get('mist'):
                rad=cw*r.uniform(.16,.24); y=yb-rad*.8-dome*cw*.05
            else:
                rad=cw*(0.075+0.095*dome)*r.uniform(.85,1.12)
                y=yb-rad*0.75-dome*cw*0.085*r.uniform(.7,1.3)
            ps.append([cx+(u-.5)*cw*0.92, y, rad])
        # two crown puffs
        if not L.get('mist'):
            for u in (.42,.6):
                rad=cw*0.085*r.uniform(.9,1.1); ps.append([cx+(u-.5)*cw*.9, yb-cw*0.2*r.uniform(.9,1.1)-rad*.2, rad])
        # keep inside tile top
        mn=min(p[1]-p[2] for p in ps)
        if mn<0.01:
            for p in ps: p[1]+=0.01-mn
        top=min(p[1]-p[2] for p in ps); bot=max(p[1]+p[2]*0.3 for p in ps)
        ps.sort(key=lambda p:-p[1]) # lower puffs first, upper on top
        for p in ps:
            sh=min(1,max(0,(p[1]-top)/max(1e-6,bot-top)))
            col=mix((255,255,255),(160,194,230),sh**1.3*0.9)
            col=mix(col,SKY,L['haze'])
            a=L['a']
            if L.get('mist'): col=(235,246,255)
            out.append((p[0],p[1],p[2],col,a))
            if not L.get('mist') and sh<0.55 and p[2]>cw*0.1:
                out.append((p[0]-p[2]*.22,p[1]-p[2]*.3,p[2]*.8,mix((255,255,255),SKY,L['haze']*.5),min(1,a*.42)))
    # wrap
    res=[]
    for (x,y,rr,c,a) in out:
        res.append((x,y,rr,c,a))
        if x-rr<0: res.append((x+4,y,rr,c,a))
        if x+rr>4: res.append((x-4,y,rr,c,a))
    return res  # draw order: first drawn first
# wrap duplicates must keep order by their original draw order -> fine since duplicates are adjacent
def css_grad(p):
    x,y,r,c,a=p
    cc=mix(c,(150,190,230),0.35)
    f=lambda v:('%.3f'%v).rstrip('0').rstrip('.')
    return ('radial-gradient(ellipse %s%% %s%% at %s%% %s%%,rgba(%d,%d,%d,%s) 0,rgba(%d,%d,%d,%s) 35%%,rgba(%d,%d,%d,%s) 70%%,rgba(%d,%d,%d,0) 100%%)'%(
        f(r/4*100),f(r*100),f(x/4*100),f(y*100),*c,f(a),*c,f(a*.9),*cc,f(a*.42),*cc))
def build_css():
    s='/* clouds: generated by tools/gen_clouds.py (shared recipe with the Android splash). Five depth layers, seamless tiles, transform-only animation. */\n'
    s+='.boot-sky{--u:25vw}\n.bl{position:absolute;left:0;height:var(--h);width:calc(100vw + var(--tw));--tw:calc(var(--h)*4);background-repeat:repeat-x;background-size:var(--tw) 100%;will-change:transform;animation:bootfly linear infinite;pointer-events:none}\n'
    for L in LAYERS:
        ps=gen(L)
        g=','.join(css_grad(p) for p in reversed(ps))
        s+='.bl.%s{top:%d%%;--h:max(%dvh,25vw);animation-duration:%ds;animation-delay:-%ds;background-image:%s}\n'%(L['n'],L['top'],L['vh'],L['dur'],L['dur']//3,g)
    s+='@keyframes bootfly{from{transform:translate3d(0,0,0)}to{transform:translate3d(calc(var(--tw)*-1),0,0)}}\n'
    return s
def build_java():
    s='        // generated by tools/gen_clouds.py: {x(tile units 0..4), y(0..1), r, R,G,B, alpha*255}\n'
    s+='        private static final float[][][] CLOUD_PUFFS = {\n'
    for L in LAYERS:
        ps=gen(L); s+='            { // '+L['n']+'\n'
        for (x,y,r,c,a) in ps: s+='                {%.3ff,%.3ff,%.3ff,%d,%d,%d,%d},\n'%(x,y,r,*c,round(a*255))
        s+='            },\n'
    s+='        };\n'
    s+='        private static final float[][] CLOUD_LAYERS = { // {top fraction, height as fraction of screen height, seconds per tile}\n'
    for L in LAYERS: s+='            {%.2ff, %.2ff, %df},\n'%(L['top']/100,L['vh']/100,L['dur'])
    s+='        };\n'
    return s
if __name__=='__main__':
    open('/workspace/imp/gen/clouds.css','w').write(build_css()); open('/workspace/imp/gen/clouds.java','w').write(build_java())
    print(len(build_css()))
